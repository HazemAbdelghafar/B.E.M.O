"""
DialogRPT Evaluation Script for General Questions Module

This script evaluates the general questions module using DialogRPT (Dialogue Response Prediction and Ranking)
to assess the quality of responses generated by the module.
"""

import os
import json
import pandas as pd
import numpy as np
from typing import List, Dict, Tuple
import torch
from transformers import AutoTokenizer, AutoModelForSequenceClassification
from sklearn.metrics import accuracy_score, precision_recall_fscore_support
import matplotlib.pyplot as plt
import seaborn as sns
from datetime import datetime

class DialogRPTEvaluator:
    """
    Evaluator class for assessing dialogue quality using DialogRPT model
    """
    
    def __init__(self, model_name: str = "microsoft/DialogRPT-human-vs-rand"):
        """
        Initialize the DialogRPT evaluator
        
        Args:
            model_name: HuggingFace model name for DialogRPT
        """
        self.model_name = model_name
        self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
        
        # Load tokenizer and model
        print(f"Loading DialogRPT model: {model_name}")
        self.tokenizer = AutoTokenizer.from_pretrained(model_name)
        self.model = AutoModelForSequenceClassification.from_pretrained(model_name)
        self.model.to(self.device)
        self.model.eval()
        
        print(f"Model loaded successfully on {self.device}")
    
    def score_response(self, context: str, response: str) -> float:
        """
        Score a single response using DialogRPT
        
        Args:
            context: The conversation context/question
            response: The response to evaluate
            
        Returns:
            Score between 0 and 1 (higher is better)
        """
        try:
            # Format input for DialogRPT
            input_text = f"{context} [SEP] {response}"
            
            # Tokenize
            inputs = self.tokenizer(
                input_text,
                return_tensors="pt",
                truncation=True,
                max_length=512,
                padding=True
            )
            
            # Move to device
            inputs = {k: v.to(self.device) for k, v in inputs.items()}
            
            # Get prediction
            with torch.no_grad():
                outputs = self.model(**inputs)
                logits = outputs.logits
                
                # Debug: print logits shape (commented out for cleaner output)
                # print(f"Logits shape: {logits.shape}")
                
                # Handle different output shapes
                if logits.shape[1] == 1:
                    # Binary classification - use sigmoid
                    score = torch.sigmoid(logits[0][0]).item()
                elif logits.shape[1] == 2:
                    # Two-class classification - use softmax
                    probabilities = torch.softmax(logits, dim=-1)
                    score = probabilities[0][1].item()
                else:
                    # Multi-class - use softmax and take max
                    probabilities = torch.softmax(logits, dim=-1)
                    score = probabilities[0].max().item()
                    
            return score
            
        except Exception as e:
            print(f"Error scoring response: {e}")
            # Return a neutral score if there's an error
            return 0.5
    
    def evaluate_dataset(self, dataset_path: str) -> Dict:
        """
        Evaluate the entire dataset
        
        Args:
            dataset_path: Path to the CSV dataset
            
        Returns:
            Dictionary containing evaluation results
        """
        # Load dataset
        df = pd.read_csv(dataset_path)
        
        results = {
            'scores': [],
            'questions': [],
            'tavily_responses': [],
            'human_responses': [],
            'meteor_scores': [],
            'response_times': []
        }
        
        print(f"Evaluating {len(df)} responses...")
        
        for idx, row in df.iterrows():
            question = row['Question']
            tavily_response = row['Tavily + Gemini Answer']
            human_response = row['Human Answer']
            meteor_score = row.get('METEOR', 0)
            
            # Score Tavily response
            tavily_score = self.score_response(question, tavily_response)
            
            # Score human response (as reference)
            human_score = self.score_response(question, human_response)
            
            results['scores'].append({
                'question_idx': idx,
                'question': question,
                'tavily_score': tavily_score,
                'human_score': human_score,
                'tavily_response': tavily_response,
                'human_response': human_response,
                'meteor_score': meteor_score
            })
            
            results['questions'].append(question)
            results['tavily_responses'].append(tavily_response)
            results['human_responses'].append(human_response)
            results['meteor_scores'].append(meteor_score)
            
            if idx % 10 == 0:
                print(f"Processed {idx + 1}/{len(df)} responses")
        
        return results
    
    def analyze_results(self, results: Dict) -> Dict:
        """
        Analyze the evaluation results
        
        Args:
            results: Results from evaluate_dataset
            
        Returns:
            Analysis summary
        """
        scores = results['scores']
        
        # Extract scores
        tavily_scores = [s['tavily_score'] for s in scores]
        human_scores = [s['human_score'] for s in scores]
        meteor_scores = results['meteor_scores']
        
        # Calculate statistics
        analysis = {
            'dialogrpt_stats': {
                'tavily_mean': np.mean(tavily_scores),
                'tavily_std': np.std(tavily_scores),
                'tavily_min': np.min(tavily_scores),
                'tavily_max': np.max(tavily_scores),
                'human_mean': np.mean(human_scores),
                'human_std': np.std(human_scores),
                'human_min': np.min(human_scores),
                'human_max': np.max(human_scores),
            },
            'meteor_stats': {
                'mean': np.mean(meteor_scores),
                'std': np.std(meteor_scores),
                'min': np.min(meteor_scores),
                'max': np.max(meteor_scores),
            },
            'correlations': {
                'dialogrpt_vs_meteor': np.corrcoef(tavily_scores, meteor_scores)[0, 1],
                'dialogrpt_vs_human': np.corrcoef(tavily_scores, human_scores)[0, 1],
            },
            'comparison': {
                'tavily_better_than_human': sum(1 for t, h in zip(tavily_scores, human_scores) if t > h),
                'total_comparisons': len(tavily_scores),
                'tavily_better_percentage': sum(1 for t, h in zip(tavily_scores, human_scores) if t > h) / len(tavily_scores) * 100
            }
        }
        
        return analysis
    
